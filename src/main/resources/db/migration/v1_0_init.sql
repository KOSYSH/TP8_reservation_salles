-- Version 1.0 : schéma initial, avant l'ajout de la description des salles.
CREATE TABLE IF NOT EXISTS utilisateurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    version INTEGER DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS salles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    capacite INTEGER NOT NULL CHECK (capacite > 0),
    version INTEGER DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salle_id BIGINT NOT NULL REFERENCES salles(id),
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    date_debut TIMESTAMP NOT NULL,
    date_fin TIMESTAMP NOT NULL,
    version INTEGER DEFAULT 0 NOT NULL,
    CONSTRAINT dates_reservation_valides CHECK (date_fin > date_debut)
);
